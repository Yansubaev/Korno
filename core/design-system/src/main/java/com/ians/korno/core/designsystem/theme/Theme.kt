/**
 * Material You (динамический цвет) доступен начиная с Android 12: только там система
 * отдаёт палитру, построенную из обоев. Ниже [KornoTheme] всё равно откатывается на
 * фирменную схему, но экранам нужно знать, показывать ли переключатель вообще.
 */
@ChecksSdkIntAtLeast(api = Build.VERSION_CODES.S)
fun isDynamicColorAvailable(): Boolean = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S

/**
 * Тема Material 3 для Korno. Фирменная схема построена из цветов иконки приложения
 * (зелёно-бирюзовый градиент на тёмном фоне) — см. [Color.kt]. При [dynamicColor] схема
 * берётся из обоев устройства; на Android 11 и ниже параметр игнорируется.
 */
@Composable
fun KornoTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && isDynamicColorAvailable() -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = KornoTypography,
        shapes = KornoShapes,
        content = content,
    )
}
