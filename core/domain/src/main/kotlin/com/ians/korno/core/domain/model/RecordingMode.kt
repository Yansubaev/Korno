package com.ians.korno.core.domain.model

/**
 * Как активность появилась.
 *
 * Не «чем человек передвигался» — это [SegmentKind]. Имя «тип активности» освободилось
 * вместе со старым перечнем (см. `docs/adr/0004`) и переиспользовано здесь.
 */
enum class RecordingMode {
    /** Виды сегментов размечает детектор; сегментов может быть много. */
    AUTO,

    /** Вид выбран до старта, сегмент один. */
    FIXED,

    /** Пришла из файла: записывать её было нечем, и пересчитывать трек бессмысленно. */
    IMPORTED,
}
