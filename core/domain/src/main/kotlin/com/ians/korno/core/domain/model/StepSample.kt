package com.ians.korno.core.domain.model

/**
 * Шаги записи авторежима на момент показания шагомера: накопленный счёт сессии, а не
 * сырой счётчик датчика — он обнуляется перезагрузкой и считает шаги ручной паузы.
 * Время — момент показания по сенсору, а не доставки. Пишется не чаще раза за эпоху
 * декодера: по этой дорожке каденс считается и после смерти процесса, и в «пересчитать».
 */
data class StepSample(
    val activityId: Long = 0L,
    val timestampEpochMillis: Long,
    val stepCount: Int,
)
