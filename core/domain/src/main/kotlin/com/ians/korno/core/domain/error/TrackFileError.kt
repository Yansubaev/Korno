package com.ians.korno.core.domain.error

/**
 * Ошибки обмена файлами треков. Отдельно от [DataError], потому что источник здесь —
 * не сеть и не своя БД, а выбранный пользователем документ, и реагировать на такие
 * ошибки нужно иначе: подсказкой про файл, а не повтором запроса.
 */
enum class TrackFileError : Error {
    /** Расширение и содержимое не опознаны ни как GPX, ни как TCX. */
    UNSUPPORTED_FORMAT,

    /** Формат опознан, но XML повреждён или не содержит ожидаемых элементов. */
    MALFORMED_CONTENT,

    /** Файл разобран, но точек с координатами в нём нет. */
    NO_TRACK_POINTS,

    /** Документ не открылся на чтение: удалён, отозвано разрешение, недоступен провайдер. */
    UNREADABLE_SOURCE,

    /** Документ не открылся на запись или не удалось создать файл в выбранной папке. */
    UNWRITABLE_DESTINATION,

    /** Не удалось прочитать активность из локальной БД или записать импортированную. */
    STORAGE_FAILURE,

    NOT_FOUND,

    UNKNOWN,
}
